'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');

function build() {
  const source=path.join(root,'game');
  const output=path.resolve(root,'dist');
  if(path.dirname(output)!==root || path.basename(output)!=='dist') throw Error('Invalid build output');
  if(fs.existsSync(output)) {
    if(fs.lstatSync(output).isSymbolicLink() || !fs.existsSync(path.join(output,'.oxynest-build'))) throw Error('Refusing to replace an unrecognized build directory');
    fs.rmSync(output,{recursive:true});
  }
  fs.mkdirSync(output);
  fs.writeFileSync(path.join(output,'.oxynest-build'),'Generated by OxyNest build tooling.\n');
  fs.copyFileSync(path.join(source,'index.html'),path.join(output,'index.html'));
  for(const dir of ['css','js','fonts']) fs.cpSync(path.join(source,dir),path.join(output,dir),{recursive:true});
  fs.writeFileSync(path.join(output,'.nojekyll'),'');
  return output;
}
if(require.main===module) {try {console.log(`Built local test artifact: ${build()}`);} catch(e){console.error(e.message);process.exitCode=1;}}
module.exports={build};
