// Writes docs/FACTS.md from the game's own files, so the list always matches what the game shows.
// Run: node tools/facts.js
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const sandbox = { window: {} };
vm.createContext(sandbox);
['js/i18n.js', 'js/content.js'].forEach(f => vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), sandbox));
const I = sandbox.window.OX_I18N, C = sandbox.window.OX_CONTENT;
const en = k => I.en[k], zh = k => I.zh[k];
const cell = s => String(s == null ? '' : s).replace(/\|/g, '\\|');

let out = `# NASA facts used in OxyNest Moon Base

Generated by \`node tools/facts.js\` from \`js/i18n.js\` and \`js/content.js\`. Do not edit by hand; edit those files and run the script again.

**Rule from the design brief:** no invented NASA facts or numbers. Every "How NASA does it" line below was taken from the team's NASA data files (D), named in the *From team data* column, and keeps D's source address. Cards with no source show **[Fact to be added]** and hide **Learn more**.

**Please check (D):** each line is a child-friendly rewording of D's text. D should confirm the wording still matches the cited NASA page, and fill the two placeholders. Explorer (ages 5-7) sees the short line with no numbers; Commander (ages 11-12) sees the line with units when there is one; Engineer sees the middle line.

| Card | How NASA does it (Engineer) | Explorer | Commander | Source | From team data |
| --- | --- | --- | --- | --- | --- |
`;
const placeholders = [];
C.CARD_ORDER.forEach(id => {
  const cd = C.CARDS[id];
  const title = en(`cd.${id}.title`);
  if (!cd.source) {
    placeholders.push(title);
    out += `| ${cell(title)} | **[Fact to be added]** | | | (none, so Learn more is hidden) | |\n`;
    return;
  }
  const kid = I.en[`cd.${id}.nasa.kid`], pro = I.en[`cd.${id}.nasa.pro`];
  const srcs = [cd.source].concat((cd.more || []).map(m => m.url)).map(u => `<${u}>`).join('<br>');
  const data = [cd.data].concat((cd.more || []).map(m => m.data)).join('<br>');
  out += `| ${cell(title)}${cd.only ? ' (Commander only)' : ''} | ${cell(en(`cd.${id}.nasa`))} | ${cell(kid || '(same)')} | ${cell(pro || '(same)')} | ${srcs} | ${cell(data)} |\n`;
});
out += `\nPlaceholders still to fill: ${placeholders.join(', ')}. Add the fact to \`cd.<id>.nasa\` in both languages in \`js/i18n.js\` and the address to \`source\` in \`js/content.js\`; \`node tools/check.js\` then requires both.\n`;

out += `\n## Numbers inside other lines\n\nThese also come from D's data and appear in wrong-answer explanations or card lines:\n\n`;
const numberKeys = Object.keys(I.en).filter(k => /^(ch|cd)\./.test(k) && /[0-9]/.test(I.en[k].replace(/CO2|O2/g, '')) && !/\.nasa(\.|$)/.test(k));
numberKeys.forEach(k => { out += `- \`${k}\`: ${I.en[k]}\n`; });

out += `\n## Game values (not NASA facts)\n\nRocks, build costs, meters (0-100), survival, stars and rewards are game rules, chosen so a child can finish each mission. The power figures shown to Commander in the build menu are D's game-balance values from \`data/modules.json\`; D's own \`reality_vs_game.json\` says these are game-balancing parameters, not NASA ratings:\n\n| Building | Commander shows |\n| --- | --- |\n`;
C.BUILD_ORDER.forEach(b => { out += `| ${en(`b.${b}.name`)} | ${C.BUILDINGS[b].kw} |\n`; });

out += `\n## Chinese\n\nAll Chinese text is in \`js/i18n.js\` (\`zh\`). It was written with an SI tool and needs a native speaker's check, like the rest of the project's Chinese text.\n`;
fs.writeFileSync(path.join(root, 'docs', 'FACTS.md'), out);
console.log(`docs/FACTS.md written: ${C.CARD_ORDER.length} cards, ${placeholders.length} placeholders, ${numberKeys.length} other lines with numbers.`);
